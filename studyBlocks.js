function getHydratedStudyBlocks(initialData, blocksToHydrate) {
  const blocks = blocksToHydrate || (typeof studyBlocks !== 'undefined' ? studyBlocks : []);
  const topicMap = new Map();

  initialData.forEach(subjectObj => {
    subjectObj.sections.forEach(section => {
      section.topics.forEach(topic => {
        topicMap.set(topic.id, {
          ...topic,
          subject: subjectObj.subject,
          color: subjectObj.color,
          icon: subjectObj.icon,
          instructor: section.instructor
        });
      });
    });
  });

  return blocks.map(block => ({
    ...block,
    topics: block.topicIds
      .map(id => topicMap.get(id))
      .filter(Boolean)
  }));
}

if (typeof window !== 'undefined') {
  window.studyBlocks = studyBlocks;
  window.getHydratedStudyBlocks = getHydratedStudyBlocks;
}
if (typeof module !== 'undefined' && module.exports) {
  module.exports = { studyBlocks, getHydratedStudyBlocks };
}
